import { spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { parseArgs } from 'node:util'
import {
  assertLicenseText,
  buildLock,
  inspectSkillText,
  licenseAssetPath,
  OPENSPEC_ASSETS_DIRECTORY,
  OPENSPEC_CORE_WORKFLOWS,
  OPENSPEC_GENERATOR_COMMAND,
  OPENSPEC_GENERATOR_PROFILE,
  OPENSPEC_LOCK_FILE,
  OPENSPEC_PACKAGE,
  OPENSPEC_REPOSITORY,
  OPENSPEC_SKILL_NAMES,
  type OpenSpecGenerator,
  type OpenSpecUpstream,
  serializeLock,
  skillAssetPath,
} from './lib/openspec.ts'
import { rootDir } from './lib/workspace.ts'

/**
 * Refresh the vendored OpenSpec core skills from an immutable release.
 *
 * Usage: pnpm openspec:update --version 1.15.0 [--commit <sha>]
 *
 * The script resolves the npm release integrity from the registry, resolves the
 * release tag to a commit, generates the core skill set with the pinned CLI in a
 * temporary directory, validates every generated byte, and only then writes the
 * assets and the provenance lock. A fetch or validation failure leaves the
 * previous pin untouched; running the same version twice produces byte-identical
 * output.
 */

const PACKAGE_DIR = join(rootDir, 'packages', 'plugin-openspec')
const ASSETS_DIR = join(PACKAGE_DIR, OPENSPEC_ASSETS_DIRECTORY)
const LOCK_FILE = join(PACKAGE_DIR, OPENSPEC_LOCK_FILE)
const REGISTRY_URL = `https://registry.npmjs.org/${OPENSPEC_PACKAGE.replace('/', '%2f')}`
const RAW_URL = 'https://raw.githubusercontent.com/Fission-AI/OpenSpec'
const REQUEST_TIMEOUT_MS = 30_000
const GENERATE_TIMEOUT_MS = 300_000
const USER_AGENT = 'dsh-setup-openspec-updater'
const COMMIT_PATTERN = /^[0-9a-f]{40}$/

interface CliOptions {
  version: string
  commit?: string
}

interface RunResult {
  command: string
  status: number | null
  stdout: string
  stderr: string
}

function printUsage(): void {
  console.log(`Usage: pnpm openspec:update --version <x.y.z> [options]

Options:
  --version <x.y.z>   OpenSpec release to pin (tag v<version>).
  --commit <sha>      Use this 40-hex commit instead of resolving the release tag.
  -h, --help          Print this help.

Writes packages/plugin-openspec/${OPENSPEC_ASSETS_DIRECTORY}/ and
packages/plugin-openspec/${OPENSPEC_LOCK_FILE}, then prints the next commands.`)
}

function parseCliOptions(): CliOptions | undefined {
  const { values } = parseArgs({
    allowPositionals: false,
    options: {
      version: { type: 'string' },
      commit: { type: 'string' },
      help: { type: 'boolean', short: 'h' },
    },
  })
  if (values.help === true) {
    printUsage()
    return undefined
  }
  const version = values.version
  if (typeof version !== 'string' || version.trim() === '') {
    throw new Error('--version is required')
  }
  const commit = typeof values.commit === 'string' ? values.commit.trim() : undefined
  if (commit !== undefined && !COMMIT_PATTERN.test(commit)) {
    throw new Error(`--commit must be a 40-hex-digit SHA, got "${commit}"`)
  }
  return { version: version.trim(), ...(commit === undefined ? {} : { commit }) }
}

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url, {
    headers: { 'user-agent': USER_AGENT, accept: 'application/json, text/plain, */*' },
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  })
  if (!response.ok) {
    throw new Error(`GET ${url} returned HTTP ${response.status}`)
  }
  return response.text()
}

function readRegistryIntegrity(payload: string, version: string): string {
  const parsed: unknown = JSON.parse(payload)
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new Error('npm registry response is not a JSON object')
  }
  const dist = (parsed as Record<string, unknown>).dist
  if (typeof dist !== 'object' || dist === null || Array.isArray(dist)) {
    throw new Error(`npm registry response for ${version} is missing dist`)
  }
  const integrity = (dist as Record<string, unknown>).integrity
  if (typeof integrity !== 'string' || !integrity.startsWith('sha512-')) {
    throw new Error(`npm registry response for ${version} is missing a sha512 integrity`)
  }
  return integrity
}

function run(command: string, cwd: string, env: NodeJS.ProcessEnv): RunResult {
  const result = spawnSync(command, {
    shell: true,
    cwd,
    env,
    encoding: 'utf8',
    timeout: GENERATE_TIMEOUT_MS,
  })
  return {
    command,
    status: result.status,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
  }
}

function quote(arg: string): string {
  return `"${arg.replaceAll('"', '\\"')}"`
}

function tagCommit(tag: string): string {
  const result = spawnSync(
    'git',
    [
      'ls-remote',
      '--tags',
      `${OPENSPEC_REPOSITORY}.git`,
      `refs/tags/${tag}`,
      `refs/tags/${tag}^{}`,
    ],
    { encoding: 'utf8', timeout: REQUEST_TIMEOUT_MS },
  )
  if (result.status !== 0) {
    throw new Error(`git ls-remote failed: ${(result.stderr ?? '').trim()}`)
  }
  const lines = (result.stdout ?? '')
    .trim()
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
  const peeled = lines.find((line) => line.endsWith(`refs/tags/${tag}^{}`))
  const direct = lines.find((line) => line.endsWith(`refs/tags/${tag}`))
  const line = peeled ?? direct
  if (line === undefined) throw new Error(`release tag ${tag} was not found upstream`)
  const commit = line.split(/\s+/)[0] ?? ''
  if (!COMMIT_PATTERN.test(commit)) {
    throw new Error(`release tag ${tag} did not resolve to a 40-hex-digit commit`)
  }
  return commit
}

async function resolveUpstream(options: CliOptions): Promise<OpenSpecUpstream> {
  const version = options.version
  const tag = `v${version}`
  const [integrity, commit] = await Promise.all([
    fetchText(`${REGISTRY_URL}/${version}`).then((payload) =>
      readRegistryIntegrity(payload, version),
    ),
    Promise.resolve(options.commit ?? tagCommit(tag)),
  ])
  return {
    repository: OPENSPEC_REPOSITORY,
    version,
    tag,
    commit,
    tarballIntegrity: integrity,
  }
}

function generatedSkills(
  projectDir: string,
  version: string,
): Array<{
  name: string
  description: string
  content: string
}> {
  const skillsDir = join(projectDir, '.dsh', 'skills')
  if (!existsSync(skillsDir)) {
    throw new Error(`generator wrote no skills directory at ${skillsDir}`)
  }
  const found = readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
  const expected = [...OPENSPEC_SKILL_NAMES].sort()
  if (JSON.stringify(found) !== JSON.stringify(expected)) {
    throw new Error(
      `generated skills are ${JSON.stringify(found)}, expected ${JSON.stringify(expected)}`,
    )
  }
  return expected.map((name) => {
    const content = readFileSync(join(skillsDir, name, 'SKILL.md'), 'utf8')
    const frontmatter = inspectSkillText(name, content, version)
    return { name, description: frontmatter.description, content }
  })
}

function writeAssets(
  skills: ReadonlyArray<{ name: string; content: string }>,
  licenseText: string,
  lockText: string,
): void {
  rmSync(ASSETS_DIR, { recursive: true, force: true })
  for (const skill of skills) {
    const target = join(PACKAGE_DIR, skillAssetPath(skill.name))
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, skill.content, 'utf8')
  }
  const licenseTarget = join(PACKAGE_DIR, licenseAssetPath())
  mkdirSync(dirname(licenseTarget), { recursive: true })
  writeFileSync(licenseTarget, licenseText, 'utf8')
  const temporaryLock = `${LOCK_FILE}.tmp`
  writeFileSync(temporaryLock, lockText, 'utf8')
  renameSync(temporaryLock, LOCK_FILE)
}

async function main(): Promise<number> {
  const options = parseCliOptions()
  if (options === undefined) return 0

  console.log(`openspec: resolving ${options.version}...`)
  const upstream = await resolveUpstream(options)
  console.log(`openspec: tag ${upstream.tag} -> ${upstream.commit}`)

  const licenseText = await fetchText(`${RAW_URL}/${upstream.commit}/LICENSE`)
  assertLicenseText(licenseText)

  const work = mkdtempSync(join(tmpdir(), 'openspec-update-'))
  const project = join(work, 'project')
  mkdirSync(project, { recursive: true })
  try {
    const spec = `${OPENSPEC_PACKAGE}@${options.version}`
    const command = [
      'npx',
      '-y',
      quote(spec),
      'init',
      quote(project),
      '--tools',
      'dsh',
      '--profile',
      OPENSPEC_GENERATOR_PROFILE,
      '--no-animation',
      '--no-copilot-cloud',
    ].join(' ')
    console.log(`openspec: generating core skills with ${spec}...`)
    const result = run(command, rootDir, {
      ...process.env,
      OPENSPEC_TELEMETRY: '0',
      OPENSPEC_NO_UPDATE_CHECK: '1',
      NO_COLOR: '1',
      CI: '1',
    })
    if (result.status !== 0) {
      throw new Error(
        `generator failed (${result.command})\n${result.stdout.trim()}\n${result.stderr.trim()}`,
      )
    }

    const skills = generatedSkills(project, options.version)
    const generator: OpenSpecGenerator = {
      command: OPENSPEC_GENERATOR_COMMAND,
      profile: OPENSPEC_GENERATOR_PROFILE,
      workflows: [...OPENSPEC_CORE_WORKFLOWS],
    }
    const lock = buildLock(upstream, generator, skills, licenseText)
    const lockText = serializeLock(lock)
    writeAssets(skills, licenseText, lockText)

    console.log(`openspec: wrote ${skills.length} skills and ${OPENSPEC_LOCK_FILE}`)
    console.log('Next: pnpm gen && pnpm build && pnpm test')
    return 0
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
}

process.exitCode = await main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error))
  return 1
})
