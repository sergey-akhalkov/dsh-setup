import { readdirSync, readFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import {
  assertFileBytes,
  assertLicenseText,
  inspectSkillText,
  licenseAssetPath,
  OPENSPEC_ASSETS_DIRECTORY,
  OPENSPEC_CORE_WORKFLOWS,
  OPENSPEC_GENERATOR_COMMAND,
  OPENSPEC_LOCK_FILE,
  OPENSPEC_REPOSITORY,
  OPENSPEC_SKILL_NAMES,
  parseLock,
  serializeLock,
  skillAssetPath,
} from '../lib/openspec.ts'

const packageDir = fileURLToPath(new URL('../../packages/plugin-openspec/', import.meta.url))
const lockText = readFileSync(join(packageDir, OPENSPEC_LOCK_FILE), 'utf8')
const lock = parseLock(JSON.parse(lockText))

function assetPath(path: string): string {
  return join(packageDir, path)
}

function walk(directory: string): string[] {
  const found: string[] = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolute = join(directory, entry.name)
    if (entry.isDirectory()) found.push(...walk(absolute))
    else if (entry.isFile()) found.push(relative(packageDir, absolute).replaceAll('\\', '/'))
  }
  return found
}

describe('vendored openspec provenance', () => {
  it('pins one immutable upstream release and generator', () => {
    expect(lock.upstream.repository).toBe(OPENSPEC_REPOSITORY)
    expect(lock.upstream.tag).toBe(`v${lock.upstream.version}`)
    expect(lock.upstream.commit).toMatch(/^[0-9a-f]{40}$/)
    expect(lock.upstream.tarballIntegrity.startsWith('sha512-')).toBe(true)
    expect(lock.generator.command).toBe(OPENSPEC_GENERATOR_COMMAND)
    expect(lock.generator.profile).toBe('core')
    expect(lock.generator.workflows).toEqual([...OPENSPEC_CORE_WORKFLOWS])
  })

  it('records exactly the six core skills and the license', () => {
    expect(lock.skills.map((skill) => skill.name)).toEqual([...OPENSPEC_SKILL_NAMES])
    expect(lock.skills.map((skill) => skill.path)).toEqual(
      OPENSPEC_SKILL_NAMES.map((name) => skillAssetPath(name)),
    )
    expect(lock.license.path).toBe(licenseAssetPath())

    const expected = [
      licenseAssetPath(),
      ...OPENSPEC_SKILL_NAMES.map((name) => skillAssetPath(name)),
    ].sort()
    expect(walk(join(packageDir, OPENSPEC_ASSETS_DIRECTORY)).sort()).toEqual(expected)
  })

  it('matches every generated byte to its recorded size and SHA-256', () => {
    for (const record of [...lock.skills, lock.license]) {
      const content = readFileSync(assetPath(record.path))
      expect(content.byteLength).toBe(record.bytes)
      expect(() => assertFileBytes(record, content)).not.toThrow()
    }
  })

  it('keeps every skill valid and generated by the pinned version', () => {
    for (const record of lock.skills) {
      const content = readFileSync(assetPath(record.path), 'utf8')
      const frontmatter = inspectSkillText(record.name, content, lock.upstream.version)
      expect(frontmatter.description).toBe(record.description)
      expect(content).not.toContain('\r')
    }
    assertLicenseText(readFileSync(assetPath(lock.license.path), 'utf8'))
  })

  it('lists every vendored asset in the package files array', () => {
    const manifest = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8')) as {
      files: string[]
    }
    for (const path of [licenseAssetPath(), ...OPENSPEC_SKILL_NAMES.map(skillAssetPath)]) {
      expect(manifest.files).toContain(path)
    }
    expect(manifest.files).toContain(OPENSPEC_LOCK_FILE)
  })

  it('serializes the committed lock canonically', () => {
    expect(serializeLock(lock)).toBe(lockText)
  })

  it('rejects a changed byte', () => {
    const record = lock.skills[0]
    if (record === undefined) throw new Error('lock has no skills')
    const content = readFileSync(assetPath(record.path), 'utf8')
    const mutated = `${content.slice(0, -1)}${content.endsWith('x') ? 'y' : 'x'}`
    expect(mutated).toHaveLength(content.length)
    expect(() => assertFileBytes(record, mutated)).toThrow(/does not match its provenance record/)
  })
})
